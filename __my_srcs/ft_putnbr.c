#include "ft___my_srcs.h"

int	ft_putnbr(int i)
{
	if (i == -2147483648)
	{
		write(1, "-2147483648", 11);
		return (0);
	}
	if (i < 0)
	{
		write(1, "-", 1);
		i = -i;
	}
	if (i > 10)
		ft_putnbr(i / 10);
	write(1, &"0123456789"[i % 10], 1);
	return (0);
}
